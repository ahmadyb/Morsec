package app.morsecode.transport.lan.payload

import app.morsecode.core.transfer.ProtocolLimits
import app.morsecode.core.transfer.identity.RecipientId
import app.morsecode.core.transfer.identity.SessionId
import app.morsecode.core.transfer.identity.TransferId
import app.morsecode.core.transfer.protocol.FrameCodec
import app.morsecode.core.transfer.protocol.FrameDecodeResult
import app.morsecode.core.transfer.session.SecureRecordCodec
import app.morsecode.core.transfer.session.SecureRecordDirection
import app.morsecode.core.transfer.session.SecureRecordType
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/*
 * Fixed wire vectors, and the one number two modules have to agree on.
 *
 * The vectors below are written out as bytes rather than generated by the codec under test. They
 * were produced from the layout in `LanPayloadRecordFormat` and the published field widths, so a
 * codec that changes an offset, a width or a byte order fails here even if it round-trips perfectly
 * with itself. Round trips prove consistency; only an external vector proves the format.
 *
 * The last group is the drift guard the payload work needs: a record's body is one MSC1 frame, and
 * the body ceiling is only correct if it equals the largest frame the transfer core actually emits
 * at the LAN chunk size. That is measured by encoding such a frame through :core-transfer, not by
 * repeating the arithmetic that produced the comment.
 */
class LanPayloadRecordVectorsTest {

    // --- fixed vectors ---------------------------------------------------------------------------

    @Test fun `fixed vector -- sequence zero, initiator to responder, empty body`() {
        val encoded = LanPayloadRecordCodec.encode(
            record(sequence = 0L, direction = SecureRecordDirection.INITIATOR_TO_RESPONDER, body = ByteArray(0)),
        )
        assertEquals(50, encoded.size)
        assertEquals(
            "4d504c31010123456789abcdef012345" +
                "6789abcdef0100000000000000000000" +
                "00000000000000000000000000000000" +
                "0000",
            hex(encoded),
        )
    }

    @Test fun `fixed vector -- the largest signed sequence, responder to initiator, sixteen byte body`() {
        val encoded = LanPayloadRecordCodec.encode(
            record(
                sequence = Long.MAX_VALUE,
                direction = SecureRecordDirection.RESPONDER_TO_INITIATOR,
                body = ByteArray(16) { (0x10 + it).toByte() },
                tag = ByteArray(LanPayloadRecordFormat.PAYLOAD_RECORD_TAG_BYTES) { 0xA5.toByte() },
            ),
        )
        assertEquals(66, encoded.size)
        assertEquals(
            "4d504c31010123456789abcdef012345" +
                "6789abcdef027fffffffffffffff0000" +
                "0010101112131415161718191a1b1c1d" +
                "1e1fa5a5a5a5a5a5a5a5a5a5a5a5a5a5" +
                "a5a5",
            hex(encoded),
        )
    }

    @Test fun `fixed vector -- a small body in the initiator direction`() {
        val encoded = LanPayloadRecordCodec.encode(
            record(
                sequence = 0L,
                direction = SecureRecordDirection.INITIATOR_TO_RESPONDER,
                body = ByteArray(16) { it.toByte() },
                tag = ByteArray(LanPayloadRecordFormat.PAYLOAD_RECORD_TAG_BYTES) { (0xF0 + it).toByte() },
            ),
        )
        assertEquals(
            "4d504c31010123456789abcdef012345" +
                "6789abcdef0100000000000000000000" +
                "0010000102030405060708090a0b0c0d" +
                "0e0ff0f1f2f3f4f5f6f7f8f9fafbfcfd" +
                "feff",
            hex(encoded),
        )
    }

    @Test fun `the declared length field is four bytes, big endian`() {
        val maximal = LanPayloadRecordCodec.encodeHeader(
            SESSION_ID,
            SecureRecordDirection.INITIATOR_TO_RESPONDER,
            0L,
            LanPayloadRecordFormat.MAX_PAYLOAD_RECORD_PLAINTEXT_BYTES,
        )
        assertEquals("000100ec", hex(maximal.copyOfRange(30, 34)))

        // The value the fixed width exists for, and the ones it must refuse.
        assertEquals("000100ed", lengthBytes(65_773L))
        assertEquals("ffffffff", lengthBytes(0xFFFF_FFFFL))
        assertEquals("80000000", lengthBytes(0x8000_0000L))

        for (declared in longArrayOf(65_773L, 0x8000_0000L, 0xFFFF_FFFFL)) {
            val mutated = headerWithLength(declared)
            val result = LanPayloadRecordCodec.decodeHeader(
                mutated,
                SESSION_ID,
                SecureRecordDirection.INITIATOR_TO_RESPONDER,
                0L,
            )
            assertTrue("expected a refusal for $declared, got $result", result is LanPayloadHeaderResult.Refused)
            assertEquals(LanPayloadRefusal.LENGTH_ABOVE_MAXIMUM, (result as LanPayloadHeaderResult.Refused).reason)
        }
    }

    @Test fun `the maximal body fills the record exactly`() {
        val body = ByteArray(LanPayloadRecordFormat.MAX_PAYLOAD_RECORD_PLAINTEXT_BYTES)
        val encoded = LanPayloadRecordCodec.encode(record(body = body))
        assertEquals(65_822, encoded.size)
        assertEquals(LanPayloadRecordFormat.MAX_PAYLOAD_RECORD_WIRE_BYTES, encoded.size)
        assertEquals("000100ec", hex(encoded.copyOfRange(30, 34)))
        val decoded = LanPayloadRecordCodec.decode(
            encoded,
            SESSION_ID,
            SecureRecordDirection.INITIATOR_TO_RESPONDER,
            0L,
        )
        assertTrue(decoded is LanPayloadDecodeResult.Decoded)
        assertEquals(
            LanPayloadRecordFormat.MAX_PAYLOAD_RECORD_PLAINTEXT_BYTES,
            (decoded as LanPayloadDecodeResult.Decoded).record.bodyBytes().size,
        )
    }

    // --- the two formats cannot be confused ------------------------------------------------------

    @Test fun `a control record does not parse as a payload record`() {
        val controlHeader = SecureRecordCodec.encodeHeader(
            SESSION_ID,
            SecureRecordDirection.INITIATOR_TO_RESPONDER,
            0L,
            SecureRecordType.PING,
            0,
        )
        assertEquals(33, controlHeader.size)
        assertEquals(34, LanPayloadRecordFormat.PAYLOAD_RECORD_HEADER_BYTES)
        assertFalse(
            "the two magics must differ",
            LanPayloadRecordFormat.magicBytes()
                .contentEquals(byteArrayOf(0x4D, 0x53, 0x52, 0x31)),
        )
        val padded = ByteArray(LanPayloadRecordFormat.PAYLOAD_RECORD_HEADER_BYTES)
        controlHeader.copyInto(padded)
        val result = LanPayloadRecordCodec.decodeHeader(
            padded,
            SESSION_ID,
            SecureRecordDirection.INITIATOR_TO_RESPONDER,
            0L,
        )
        assertTrue(result is LanPayloadHeaderResult.Refused)
        assertEquals(
            LanPayloadRefusal.WRONG_MAGIC,
            (result as LanPayloadHeaderResult.Refused).reason,
        )
    }

    @Test fun `a payload record does not parse as a control record`() {
        val payloadWire = LanPayloadRecordCodec.encode(record(body = ByteArray(4)))
        val asControl = SecureRecordCodec.decodeHeader(
            payloadWire.copyOfRange(0, SecureRecordCodec.HEADER_SIZE_BYTES),
            SESSION_ID,
            SecureRecordDirection.INITIATOR_TO_RESPONDER,
        )
        assertNull(asControl)
    }

    // --- one record carries exactly one MSC1 frame -----------------------------------------------

    @Test fun `a maximal MSC1 frame is exactly the record body ceiling`() {
        val frame = maximalMsc1Frame()
        val encoded = FrameCodec.encode(frame)
        assertEquals(
            "the core's own encoder, not the arithmetic in a comment",
            ProtocolLimits.HEADER_SIZE_BYTES +
                (3 * ProtocolLimits.MAX_ID_LENGTH_BYTES) +
                LanPayloadRecordFormat.LAN_PAYLOAD_CHUNK_BYTES,
            encoded.size,
        )
        assertEquals(LanPayloadRecordFormat.MAX_PAYLOAD_RECORD_PLAINTEXT_BYTES, encoded.size)
        assertEquals(65_772, encoded.size)
    }

    @Test fun `a maximal MSC1 frame fits one record and comes back byte identical`() {
        val frameBytes = FrameCodec.encode(maximalMsc1Frame())
        val wire = LanPayloadRecordCodec.encode(
            record(
                sequence = 0L,
                direction = SecureRecordDirection.INITIATOR_TO_RESPONDER,
                body = frameBytes,
            ),
        )
        assertEquals(LanPayloadRecordFormat.MAX_PAYLOAD_RECORD_WIRE_BYTES, wire.size)
        val result = LanPayloadRecordCodec.decode(
            wire,
            SESSION_ID,
            SecureRecordDirection.INITIATOR_TO_RESPONDER,
            0L,
        )
        assertTrue(result is LanPayloadDecodeResult.Decoded)
        val body = (result as LanPayloadDecodeResult.Decoded).record.bodyBytes()
        assertTrue("the body must still be the frame", body.contentEquals(frameBytes))
        val reparsed = FrameCodec.decodeSingle(body)
        assertTrue(reparsed is FrameDecodeResult.Success)
        assertEquals(
            LanPayloadRecordFormat.LAN_PAYLOAD_CHUNK_BYTES,
            (reparsed as FrameDecodeResult.Success).frame.payload.size,
        )
    }

    // --- the two ceilings cannot drift apart -----------------------------------------------------

    @Test fun `the LAN chunk profile sits inside the core's chunk bounds`() {
        assertTrue(
            LanPayloadRecordFormat.LAN_PAYLOAD_CHUNK_BYTES >= ProtocolLimits.MIN_CHUNK_SIZE_BYTES,
        )
        assertTrue(
            LanPayloadRecordFormat.LAN_PAYLOAD_CHUNK_BYTES <= ProtocolLimits.MAX_CHUNK_SIZE_BYTES,
        )
        assertEquals(ProtocolLimits.DEFAULT_CHUNK_SIZE_BYTES, LanPayloadRecordFormat.LAN_PAYLOAD_CHUNK_BYTES)
    }

    @Test fun `the body ceiling is derived from the core's header and identifier budgets`() {
        assertEquals(
            ProtocolLimits.HEADER_SIZE_BYTES +
                (3 * ProtocolLimits.MAX_ID_LENGTH_BYTES) +
                LanPayloadRecordFormat.LAN_PAYLOAD_CHUNK_BYTES,
            LanPayloadRecordFormat.MAX_PAYLOAD_RECORD_PLAINTEXT_BYTES,
        )
    }

    @Test fun `the length field is wide enough and no wider than it needs to be`() {
        // Four bytes are necessary: the ceiling does not fit an unsigned 16-bit field.
        assertTrue(LanPayloadRecordFormat.MAX_PAYLOAD_RECORD_PLAINTEXT_BYTES > 0xFFFF)
        // And sufficient: it is far inside an unsigned 32-bit field.
        assertTrue(LanPayloadRecordFormat.MAX_PAYLOAD_RECORD_PLAINTEXT_BYTES.toLong() <= 0xFFFF_FFFFL)
        assertEquals(4, LanPayloadRecordFormat.DECLARED_LENGTH_BYTES)
    }

    @Test fun `the wire maximum is header plus body plus tag`() {
        assertEquals(
            LanPayloadRecordFormat.PAYLOAD_RECORD_HEADER_BYTES +
                LanPayloadRecordFormat.MAX_PAYLOAD_RECORD_PLAINTEXT_BYTES +
                LanPayloadRecordFormat.PAYLOAD_RECORD_TAG_BYTES,
            LanPayloadRecordFormat.MAX_PAYLOAD_RECORD_WIRE_BYTES,
        )
    }

    @Test fun `an empty envelope body is still not a valid MSC1 frame`() {
        // The two layers have different jobs and this is where they meet: the envelope accepts a
        // zero-length body as structurally well formed, and the frame decoder refuses it. Nothing
        // in the envelope may start validating frames, because that would be a second frame parser.
        val empty = LanPayloadRecordCodec.encode(record(body = ByteArray(0)))
        val decoded = LanPayloadRecordCodec.decode(
            empty,
            SESSION_ID,
            SecureRecordDirection.INITIATOR_TO_RESPONDER,
            0L,
        )
        assertTrue(decoded is LanPayloadDecodeResult.Decoded)
        assertFalse(
            FrameCodec.decode(ByteArray(0)) is FrameDecodeResult.Success,
        )
    }

    // --- helpers ---------------------------------------------------------------------------------

    private val SESSION_ID: SessionId = SessionId("0123456789abcdef0123456789abcdef")

    private fun record(
        sequence: Long = 0L,
        direction: SecureRecordDirection = SecureRecordDirection.INITIATOR_TO_RESPONDER,
        body: ByteArray = ByteArray(0),
        tag: ByteArray = ByteArray(LanPayloadRecordFormat.PAYLOAD_RECORD_TAG_BYTES),
    ): LanPayloadRecord = LanPayloadRecord(SESSION_ID, direction, sequence, body, tag)

    private fun headerWithLength(declared: Long): ByteArray {
        val header = LanPayloadRecordCodec.encodeHeader(
            SESSION_ID,
            SecureRecordDirection.INITIATOR_TO_RESPONDER,
            0L,
            0,
        )
        for (index in 0 until LanPayloadRecordFormat.DECLARED_LENGTH_BYTES) {
            val shift = (LanPayloadRecordFormat.DECLARED_LENGTH_BYTES - 1 - index) * 8
            header[LanPayloadRecordFormat.OFF_DECLARED_LENGTH + index] =
                ((declared ushr shift) and 0xFF).toByte()
        }
        return header
    }

    private fun lengthBytes(declared: Long): String =
        hex(headerWithLength(declared).copyOfRange(30, 34))

    private fun maximalMsc1Frame() = FrameCodec.dataChunk(
        sessionId = SessionId("a".repeat(ProtocolLimits.MAX_ID_LENGTH_BYTES)),
        transferId = TransferId("b".repeat(ProtocolLimits.MAX_ID_LENGTH_BYTES)),
        recipientId = RecipientId("c".repeat(ProtocolLimits.MAX_ID_LENGTH_BYTES)),
        offset = 0L,
        sequence = 0L,
        bytes = ByteArray(LanPayloadRecordFormat.LAN_PAYLOAD_CHUNK_BYTES),
    )

    private fun hex(bytes: ByteArray): String {
        val builder = StringBuilder(bytes.size * 2)
        for (byte in bytes) {
            val value = byte.toInt() and 0xFF
            builder.append("0123456789abcdef"[value ushr 4])
            builder.append("0123456789abcdef"[value and 0x0F])
        }
        return builder.toString()
    }
}
