/*
 * MPS4, MPA1 and MPSF -- the control records the PAKE exchange needs around its three rounds.
 *
 * WHY THEY EXIST
 *   MPS3 carries rounds one, two and three and nothing else. Two things happen outside those rounds
 *   and both must be bound to the same context:
 *
 *   1. The responder has to learn which fresh attempt it is participating in *before* it can create
 *      a round one, because the attempt id is part of the authentication context and therefore part
 *      of both participant ids. MPS4 carries it.
 *
 *   2. Both peers have to state an explicit decision after round three. MPA1 carries it.
 *
 *   3. When an attempt fails, the two peers have to agree that it failed before either can decide
 *      to retry. Without a signal, the peer still waiting for a round the other side abandoned
 *      blocks until its deadline. MPSF carries that agreement, and it deliberately carries nothing
 *      else: a wrong code, an invalid proof, a bad round-three tag, a context mismatch, a replay and
 *      malformed input all produce the *same* record. Only the policy state travels -- "another
 *      attempt is acceptable" or "this connection ends" -- because that is the only thing the peer
 *      needs in order not to wait, and it is the only thing that must not be inferred from timing.
 *
 * WHY CARRYING THEM INSIDE TLS IS NOT ENOUGH ON ITS OWN
 *   TLS at this point is encrypted but unauthenticated -- that is the whole reason a PAKE is running.
 *   A relay can terminate two connections and rewrite anything these records say. Substituting an
 *   attempt id is therefore expected to work at the record layer and to fail one layer up: the id is
 *   an input to the authentication context, so a substituted id changes both participant ids and the
 *   PAKE proofs no longer verify. Substituting a decision is bounded the same way, because MPA1 is
 *   accepted only after round three validated, and it must name the attempt, the code instance, the
 *   transcript digest, both session identifiers, the suite and the opposite role.
 *
 * WHAT THESE RECORDS DO NOT CARRY
 *   No code, no password, no keying material, no tag, no channel-binding value and no participant id.
 *   A peer that loses every record on the wire learns nothing about the secret; a peer that replays
 *   one gets a refusal, because every field it would need to match is fresh per attempt.
 *
 * FORMAT
 *   Same envelope as the other pairing frames: 4-byte big-endian length prefix, 4-byte magic, 1-byte
 *   schema version, then tag/length/value entries in strictly ascending tag order, then an END tag
 *   with zero length and no byte after it. Duplicate, out-of-order and unknown tags are refusals, not
 *   skips. Every field has a fixed width or a documented text bound, so a decoder never allocates
 *   from an attacker-chosen length.
 *
 * STATUS
 *   Experimental, project-defined and not independently cryptographically reviewed. The owner
 *   accepted that risk on 2026-10-19; see doc/security/owner-risk-waiver-2026-10-19.md.
 */

