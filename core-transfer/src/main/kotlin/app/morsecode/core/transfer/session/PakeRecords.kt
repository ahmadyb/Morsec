/**
 * The responder's introduction to a fresh attempt.
 *
 * [attemptId] is generated by the initiator's ledger. Both sides end up binding exactly these fields
 * into the authentication context, so the record is the single description of "which attempt is
 * this" and there is no second place for the two peers to disagree.
 */
public class PakeAttemptStart(
    public val suite: PairingAuthenticationCapability,
    public val profile: JpakeCurveProfile,
    public val role: SecurePeerRole,
    public val secureSessionId: SessionId,
    public val controlSessionId: String,
    public val attemptId: PakeAttemptId,
    public val attemptOrdinal: Int,
    codeInstanceId: ByteArray,
    transcriptDigest: ByteArray,
) {
    private val codeInstance: ByteArray = requireWidth(codeInstanceId, CODE_INSTANCE_BYTES, "code instance id")
    private val transcript: ByteArray = requireWidth(transcriptDigest, DIGEST_BYTES, "transcript digest")

    init {
        require(suite != PairingAuthenticationCapability.NONE) { "an attempt start requires a real suite" }
        require(secureSessionId.value.matches(HEX_128)) { "secure session id must be 128-bit lowercase hex" }
        require(JpakeMessageCodec.isBoundedText(controlSessionId, MAX_CONTROL_SESSION_ID_BYTES)) {
            "control session id out of bounds"
        }
        require(attemptOrdinal in 1..PakeAttemptLedger.MAX_PAKE_ATTEMPTS) { "attempt ordinal out of range" }
    }

    public fun codeInstanceBytes(): ByteArray = codeInstance.copyOf()

    public fun transcriptDigestBytes(): ByteArray = transcript.copyOf()

    /** SHA-256 over this record's canonical encoding. Bound into the authentication context. */
    public fun digest(): ByteArray {
        val encoded = PakeRecordFormat.encode(ATTEMPT_START_MAGIC, attemptsStartFields(this))
        return try {
            MessageDigest.getInstance("SHA-256").digest(encoded)
        } finally {
            encoded.fill(0)
        }
    }

    public fun clearSensitive() {
        codeInstance.fill(0)
        transcript.fill(0)
    }

    override fun toString(): String =
        "PakeAttemptStart(ordinal=$attemptOrdinal, role=${role.name}, ids=[redacted])"
}

/** One peer's explicit decision, bound to everything that identifies the exchange. */
public class PakeApproval(
    public val decision: PakeApprovalDecision,
    public val suite: PairingAuthenticationCapability,
    public val profile: JpakeCurveProfile,
    public val role: SecurePeerRole,
    public val secureSessionId: SessionId,
    public val controlSessionId: String,
    public val attemptId: PakeAttemptId,
    public val attemptOrdinal: Int,
    codeInstanceId: ByteArray,
    transcriptDigest: ByteArray,
) {
    private val codeInstance: ByteArray = requireWidth(codeInstanceId, CODE_INSTANCE_BYTES, "code instance id")
    private val transcript: ByteArray = requireWidth(transcriptDigest, DIGEST_BYTES, "transcript digest")

    init {
        require(suite != PairingAuthenticationCapability.NONE) { "an approval requires a real suite" }
        require(secureSessionId.value.matches(HEX_128)) { "secure session id must be 128-bit lowercase hex" }
        require(JpakeMessageCodec.isBoundedText(controlSessionId, MAX_CONTROL_SESSION_ID_BYTES)) {
            "control session id out of bounds"
        }
        require(attemptOrdinal in 1..PakeAttemptLedger.MAX_PAKE_ATTEMPTS) { "attempt ordinal out of range" }
    }

    public fun codeInstanceBytes(): ByteArray = codeInstance.copyOf()

    public fun transcriptDigestBytes(): ByteArray = transcript.copyOf()

    /**
     * True when this record describes exactly the exchange the caller is holding.
     *
     * Everything is compared, including the role: an approval reflected back to its sender names the
     * wrong role and is refused, which is what stops a peer from satisfying "the remote approved" with
     * the local peer's own record.
     */
    public fun bindsTo(
        expectedAttemptId: PakeAttemptId,
        expectedOrdinal: Int,
        expectedCodeInstance: ByteArray,
        expectedTranscriptDigest: ByteArray,
        expectedSecureSessionId: SessionId,
        expectedControlSessionId: String,
        expectedSuite: PairingAuthenticationCapability,
        expectedProfile: JpakeCurveProfile,
        expectedPeerRole: SecurePeerRole,
    ): Boolean {
        if (suite != expectedSuite) return false
        if (profile != expectedProfile) return false
        if (role != expectedPeerRole) return false
        if (attemptOrdinal != expectedOrdinal) return false
        if (secureSessionId != expectedSecureSessionId) return false
        if (controlSessionId != expectedControlSessionId) return false
        if (attemptId != expectedAttemptId) return false
        val codeMatches = MessageDigest.isEqual(codeInstance, expectedCodeInstance)
        val transcriptMatches = MessageDigest.isEqual(transcript, expectedTranscriptDigest)
        return codeMatches && transcriptMatches
    }

    public fun clearSensitive() {
        codeInstance.fill(0)
        transcript.fill(0)
    }

    override fun toString(): String =
        "PakeApproval(decision=${decision.name}, ordinal=$attemptOrdinal, ids=[redacted])"
}

