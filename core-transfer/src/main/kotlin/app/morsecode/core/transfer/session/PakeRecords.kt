private const val SCHEMA_VERSION: Int = 1
private const val HEADER_BYTES: Int = 4 + 4 + 1
private const val TLV_OVERHEAD: Int = 4
private const val TAG_END: Int = 0x0000

private const val TAG_SUITE: Int = 0x0001
private const val TAG_PROFILE: Int = 0x0002
private const val TAG_ROLE: Int = 0x0003
private const val TAG_SECURE_SESSION_ID: Int = 0x0004
private const val TAG_CONTROL_SESSION_ID: Int = 0x0005
private const val TAG_ATTEMPT_ID: Int = 0x0006
private const val TAG_CODE_INSTANCE: Int = 0x0007
private const val TAG_ORDINAL: Int = 0x0008
private const val TAG_TRANSCRIPT_DIGEST: Int = 0x0009
private const val TAG_DECISION: Int = 0x000A
private const val MAX_TAG: Int = TAG_DECISION

private val ATTEMPT_START_MAGIC = byteArrayOf(0x4D, 0x50, 0x53, 0x34) // "MPS4"
private val APPROVAL_MAGIC = byteArrayOf(0x4D, 0x50, 0x41, 0x31) // "MPA1"
private val FAILURE_MAGIC = byteArrayOf(0x4D, 0x50, 0x53, 0x46) // "MPSF"

/**
 * The failure record's only tag. Tag numbers are scoped to a magic, so reusing 0x0001 here does
 * not collide with the suite field of MPS4/MPA1: a frame is decoded against exactly one magic.
 */
private const val TAG_VERDICT: Int = 0x0001

private const val CODE_INSTANCE_BYTES: Int = PakeAttemptLedger.CODE_INSTANCE_BYTES
private const val DIGEST_BYTES: Int = 32
private const val SESSION_ID_BYTES: Int = 16
private const val MAX_CONTROL_SESSION_ID_BYTES: Int = 64

/** Sized for the largest legitimate record: every field present at its maximum. */
private const val MAX_RECORD_BYTES: Int = 256

private val HEX_128 = Regex("[0-9a-f]{32}")

private object PakeRecordFormat {
    sealed interface Parsed {
        class Fields(val values: Map<Int, ByteArray>) : Parsed
        class Rejected(val reason: PakeRecordReject) : Parsed
    }

    fun encode(magic: ByteArray, fields: List<Pair<Int, ByteArray>>): ByteArray {
        // The declared length covers the payload only: magic, version, fields and the END tag. The
        // 4-byte prefix that carries it is not part of its own count. Sizing this from HEADER_BYTES
        // (which includes the prefix) used to leave four zero bytes after the END tag, and a decoder
        // that stops at END then saw a well-formed frame with trailing garbage.
        var size = magic.size + 1 + TLV_OVERHEAD
        for ((_, value) in fields) size += TLV_OVERHEAD + value.size
        require(size <= MAX_RECORD_BYTES) { "PAKE control record exceeds its bound" }
        val body = ByteBuffer.allocate(size).order(ByteOrder.BIG_ENDIAN)
        body.put(magic)
        body.put(SCHEMA_VERSION.toByte())
        for ((tag, value) in fields) {
            body.putShort(tag.toShort())
            body.putShort(value.size.toShort())
            body.put(value)
        }
        body.putShort(TAG_END.toShort())
        body.putShort(0)
        val payload = body.array()
        val out = ByteArray(4 + payload.size)
        out[0] = ((payload.size ushr 24) and 0xFF).toByte()
        out[1] = ((payload.size ushr 16) and 0xFF).toByte()
        out[2] = ((payload.size ushr 8) and 0xFF).toByte()
        out[3] = (payload.size and 0xFF).toByte()
        payload.copyInto(out, 4)
        return out
    }

    fun decode(frame: ByteArray, magic: ByteArray): Parsed {
        if (frame.size < 4 + HEADER_BYTES) return Parsed.Rejected(PakeRecordReject.FRAME_TOO_SHORT)
        if (frame.size > 4 + MAX_RECORD_BYTES) return Parsed.Rejected(PakeRecordReject.FRAME_TOO_LARGE)
        val declared = ((frame[0].toInt() and 0xFF) shl 24) or
            ((frame[1].toInt() and 0xFF) shl 16) or
            ((frame[2].toInt() and 0xFF) shl 8) or
            (frame[3].toInt() and 0xFF)
        if (declared < HEADER_BYTES) return Parsed.Rejected(PakeRecordReject.FRAME_TOO_SHORT)
        if (declared > MAX_RECORD_BYTES) return Parsed.Rejected(PakeRecordReject.FRAME_TOO_LARGE)
        if (declared != frame.size - 4) return Parsed.Rejected(PakeRecordReject.FRAME_TOO_SHORT)
        for (index in magic.indices) {
            if (frame[4 + index] != magic[index]) return Parsed.Rejected(PakeRecordReject.BAD_MAGIC)
        }
        if ((frame[8].toInt() and 0xFF) != SCHEMA_VERSION) return Parsed.Rejected(PakeRecordReject.BAD_VERSION)

        val values = HashMap<Int, ByteArray>()
        var position = 9
        var previousTag = -1
        var sawEnd = false
        while (position < frame.size) {
            if (position + TLV_OVERHEAD > frame.size) return Parsed.Rejected(PakeRecordReject.MISSING_FIELD)
            val tag = ((frame[position].toInt() and 0xFF) shl 8) or (frame[position + 1].toInt() and 0xFF)
            val length = ((frame[position + 2].toInt() and 0xFF) shl 8) or
                (frame[position + 3].toInt() and 0xFF)
            position += TLV_OVERHEAD
            if (tag == TAG_END) {
                if (length != 0) return Parsed.Rejected(PakeRecordReject.MALFORMED_END_TAG)
                sawEnd = true
                if (position != frame.size) return Parsed.Rejected(PakeRecordReject.TRAILING_BYTES)
                break
            }
            if (tag == previousTag) return Parsed.Rejected(PakeRecordReject.DUPLICATE_FIELD)
            if (tag < previousTag) return Parsed.Rejected(PakeRecordReject.FIELD_ORDER_NOT_CANONICAL)
            previousTag = tag
            if (tag > MAX_TAG) return Parsed.Rejected(PakeRecordReject.UNKNOWN_FIELD)
            if (position + length > frame.size) {
                return Parsed.Rejected(PakeRecordReject.FIELD_LENGTH_OUT_OF_BOUNDS)
            }
            values[tag] = frame.copyOfRange(position, position + length)
            position += length
        }
        if (!sawEnd) return Parsed.Rejected(PakeRecordReject.MISSING_FIELD)
        return Parsed.Fields(values)
    }
}

private fun commonFields(
    suite: PairingAuthenticationCapability,
    profile: JpakeCurveProfile,
    role: SecurePeerRole,
    secureSessionId: SessionId,
    controlSessionId: String,
    attemptId: PakeAttemptId,
    attemptOrdinal: Int,
    codeInstanceId: ByteArray,
    transcriptDigest: ByteArray,
): MutableList<Pair<Int, ByteArray>> {
    val fields = ArrayList<Pair<Int, ByteArray>>(10)
    fields.add(TAG_SUITE to byteArrayOf((suite.wireId ushr 8).toByte(), suite.wireId.toByte()))
    fields.add(TAG_PROFILE to byteArrayOf(profile.wireId.toByte()))
    fields.add(TAG_ROLE to byteArrayOf(role.wireId.toByte()))
    fields.add(TAG_SECURE_SESSION_ID to hexToBytes(secureSessionId.value))
    fields.add(TAG_CONTROL_SESSION_ID to controlSessionId.toByteArray(Charsets.UTF_8))
    fields.add(TAG_ATTEMPT_ID to attemptId.bytes())
    fields.add(TAG_CODE_INSTANCE to codeInstanceId.copyOf())
    fields.add(TAG_ORDINAL to byteArrayOf(attemptOrdinal.toByte()))
    fields.add(TAG_TRANSCRIPT_DIGEST to transcriptDigest.copyOf())
    return fields
}

