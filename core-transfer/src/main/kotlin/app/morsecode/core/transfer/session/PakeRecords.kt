private fun readSuite(values: Map<Int, ByteArray>): PairingAuthenticationCapability? {
    val bytes = values[TAG_SUITE] ?: return null
    if (bytes.size != 2) return null
    val id = ((bytes[0].toInt() and 0xFF) shl 8) or (bytes[1].toInt() and 0xFF)
    val suite = PairingAuthenticationCapability.fromWireId(id) ?: return null
    return if (suite == PairingAuthenticationCapability.NONE) null else suite
}

private fun readProfile(values: Map<Int, ByteArray>): JpakeCurveProfile? {
    val bytes = values[TAG_PROFILE] ?: return null
    if (bytes.size != 1) return null
    return JpakeCurveProfile.fromWireId(bytes[0].toInt() and 0xFF)
}

private fun readRole(values: Map<Int, ByteArray>): SecurePeerRole? {
    val bytes = values[TAG_ROLE] ?: return null
    if (bytes.size != 1) return null
    return SecurePeerRole.fromWireId(bytes[0].toInt() and 0xFF)
}

private fun readSecureSessionId(values: Map<Int, ByteArray>): SessionId? {
    val bytes = values[TAG_SECURE_SESSION_ID] ?: return null
    if (bytes.size != SESSION_ID_BYTES) return null
    return SessionId.orNull(hexOf(bytes))
}

private fun readControlSessionId(values: Map<Int, ByteArray>): String? {
    val bytes = values[TAG_CONTROL_SESSION_ID] ?: return null
    if (bytes.size > MAX_CONTROL_SESSION_ID_BYTES) return null
    val text = String(bytes, Charsets.UTF_8)
    return if (JpakeMessageCodec.isBoundedText(text, MAX_CONTROL_SESSION_ID_BYTES)) text else null
}

private fun readAttemptId(values: Map<Int, ByteArray>): PakeAttemptId? {
    val bytes = values[TAG_ATTEMPT_ID] ?: return null
    return PakeAttemptId.fromBytes(bytes)
}

private fun readOrdinal(values: Map<Int, ByteArray>): Int? {
    val bytes = values[TAG_ORDINAL] ?: return null
    if (bytes.size != 1) return null
    val ordinal = bytes[0].toInt() and 0xFF
    return if (ordinal in 1..PakeAttemptLedger.MAX_PAKE_ATTEMPTS) ordinal else null
}

private fun readDecision(values: Map<Int, ByteArray>): PakeApprovalDecision? {
    val bytes = values[TAG_DECISION] ?: return null
    if (bytes.size != 1) return null
    return PakeApprovalDecision.fromWireId(bytes[0].toInt() and 0xFF)
}

private fun requireWidth(value: ByteArray, expected: Int, field: String): ByteArray {
    require(value.size == expected) { "$field must be exactly $expected bytes" }
    return value.copyOf()
}

private fun hexToBytes(hex: String): ByteArray {
    val out = ByteArray(hex.length / 2)
    for (index in out.indices) {
        out[index] = (
            (Character.digit(hex[index * 2], 16) shl 4) or
                Character.digit(hex[index * 2 + 1], 16)
            ).toByte()
    }
    return out
}

private fun hexOf(bytes: ByteArray): String {
    val digits = "0123456789abcdef"
    val builder = StringBuilder(bytes.size * 2)
    for (byte in bytes) {
        val unsigned = byte.toInt() and 0xFF
        builder.append(digits[unsigned ushr 4]).append(digits[unsigned and 0x0F])
    }
    return builder.toString()
}
